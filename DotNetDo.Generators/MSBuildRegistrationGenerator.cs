using Microsoft.CodeAnalysis;

namespace DotNetDo.Generators;

/// <summary>Generates a module initializer that registers the installed MSBuild toolset before project APIs are used.</summary>
[Generator]
public sealed class MSBuildRegistrationGenerator : IIncrementalGenerator
{
    /// <summary>Adds generated startup code that registers the newest installed MSBuild toolset.</summary>
    /// <param name="context">The compiler pipeline used to emit the module initializer.</param>
    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterPostInitializationOutput(output => output.AddSource("DotNetDo.MSBuildRegistration.g.cs", Source));

    const string Source = """
        // <auto-generated />
        namespace DotNetDo.Generated;

        static class MSBuildRegistration
        {
            [global::System.Runtime.CompilerServices.ModuleInitializer]
            internal static void Initialize()
            {
                if (global::Microsoft.Build.Locator.MSBuildLocator.IsRegistered)
                    return;

                // MSBuildLocator points these variables at the registered SDK. Remember the inherited values so
                // DotNetDo can restore them for child processes, which may resolve a different SDK.
                var inherited = new global::System.Collections.Generic.Dictionary<string, string>();
                foreach (var name in new[] { "MSBUILD_EXE_PATH", "MSBuildExtensionsPath", "MSBuildSDKsPath" })
                    inherited[name] = global::System.Environment.GetEnvironmentVariable(name);
                global::System.AppContext.SetData("DotNetDo.InheritedMSBuildEnvironment", inherited);

                global::Microsoft.Build.Locator.MSBuildLocator.RegisterDefaults();
            }
        }
        """;
}
